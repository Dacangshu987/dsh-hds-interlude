/**
 * 版本标识 —— 对齐上游 `src/meta.ts` 的 `HDS_INTERLUDE_VERSION`。
 *
 * ## 这个数字是什么
 *
 * 它标的是**本仓对齐的上游基线版本**（不是 npm 包的版本号）。为什么需要它：
 * 分享码导入时要把「预设自称适配的版本」与「本仓对齐的基线」比一比，不同就提醒
 * 用户「个别字段可能有出入」。没有这个常量，那条提醒就只能猜。
 *
 * ## 为什么不用 `package.json` 的 version
 *
 * 那个是**本包的发布版本**（`0.1.0` 起步），与上游 rc 序列是两条线。
 * 拿它去比 `hdsi_version` 只会永远报「版本差异」，提醒就变成了噪声。
 *
 * 上游基线一变（比如对齐到 rc51），这里要跟着改——它是**单一事实来源**。
 *
 * @module dsh-hds-interlude/meta
 */

/** 本仓对齐的上游基线版本。 */
export const HDS_INTERLUDE_VERSION = '1.0.1-rc50'
